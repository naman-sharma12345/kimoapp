// Bundles the AI editor's knowledge pack (apps/api/src/ai/knowledge/*.md)
// into a TypeScript string module, so the Worker never reads files at run
// time. Run `pnpm ai:knowledge` after editing a knowledge file; a test
// fails if the bundle is out of date.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../apps/api/src/ai/knowledge/', import.meta.url);
const out = new URL(
  '../apps/api/src/ai/knowledge.generated.ts',
  import.meta.url,
);
export function knowledgePack() {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => readFileSync(new URL(name, dir), 'utf8').trim())
    .join('\n\n');
}
if (
  process.argv[1] &&
  import.meta.url.endsWith(process.argv[1].split('/').pop())
) {
  writeFileSync(
    out,
    `// Generated by scripts/ai-knowledge.mjs from apps/api/src/ai/knowledge/*.md.\n// Do not edit by hand.\nexport const KNOWLEDGE_PACK = ${JSON.stringify(knowledgePack())};\n`,
  );
}
